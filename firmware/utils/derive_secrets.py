def generateCaseList(permission: str, permissionlist: PermissionList):
    """
    @brief Generates a C switch-case block for selecting the correct key derivation
    routine based on group ID and the requested operation.

    @param permission (str): The permission type (Read, Write, etc.).
    @param permissionlist (PermissionList): The list of permissions.

    @return str: The generated C code.
    """
    assert permission in VALID_PERMS, "Invalid permission passed to genCaseList"

    validgen: Callable[[int], str] = lambda groupid: GEN_CASE_SMT(groupid, permission)
    stubgen: Callable[[int], str] = GEN_CASE_STUB

    genmap: Callable[[Permission], dict[str, bool]] = lambda p: dict(
        zip(VALID_PERMS, (p.write, p.read, True, p.receive))
    )
    cases = [
        validgen(p.group_id) if genmap(p)[permission] else stubgen(p.group_id)
        for p in permissionlist
    ]

    return CASELIST(permission, "\n".join(cases))


def generateSecrets(
    outfilename: str,
    permissionlist: PermissionList,
    secrets: dict[str, dict[str, dict[str, bytes]]],
):
    """
    @brief Compiles all derived key routines and lookup tables into a single C source file.

    @param outfilename (str): The output file path.
    @param permissionlist (PermissionList): The list of permissions.
    @param secrets (dict): The master secrets.
    """
    builder = [
        DISCLAIMER,
        DEFINITIONS,
        RECV_GROUPS([p.group_id for p in permissionlist if p.receive]),
        GEN_STUB(),
    ]

    for p in permissionlist:
        if p.write:
            builder.append(GEN_WRITEKEY(p.group_id, secrets))
        if p.read:
            builder.append(GEN_READKEY(p.group_id, secrets))
        if p.receive:
            builder.append(GEN_RECVKEY(p.group_id, secrets))
        builder.append(GEN_SENDKEY(p.group_id, secrets))

    builder.append(GEN_INTERROGATEKEY(secrets))
    builder.append(GEN_REPLYKEY(secrets))

    builder.append(generateCaseList("Write", permissionlist))
    builder.append(generateCaseList("Read", permissionlist))
    builder.append(generateCaseList("Recv", permissionlist))
    builder.append(generateCaseList("Send", permissionlist))

    with open(outfilename, "w") as outfile:
        _ = outfile.write("\n\n".join(builder))


def arg_parse() -> argparse.Namespace:
    """
    @brief Defines and parses command line arguments for secret derivation.

    @return argparse.Namespace: The parsed arguments.
    """
    parser = argparse.ArgumentParser()

    _ = parser.add_argument(
        "secrets", type=argparse.FileType("rb"), help="Path to secrets file"
    )
    _ = parser.add_argument("hsm_pin", type=str, help="User PIN for the HSM")
    _ = parser.add_argument(
        "permissions",
        type=str,
        help='List of colon-separated permissions. E.g., "1234=R--:4321=RWC"',
    )

    return parser.parse_args()


