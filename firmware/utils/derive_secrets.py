@dataclass
class Permission:
    """
    @brief Represents permissions for a specific group.

    @param group_id (int): The 16-bit group identifier.
    @param read (bool): Permission to read files in this group.
    @param write (bool): Permission to write files in this group.
    @param receive (bool): Permission to receive files from peers for this group.
    """

    group_id: int = 0
    read: bool = False
    write: bool = False
    receive: bool = False

    @classmethod
    def deserialize(cls, perms: str):
        group_id, perm_string = perms.split("=")

        perm_obj = cls(
            int(group_id, 16),
            read=perm_string[0] == "R",
            write=perm_string[1] == "W",
            receive=perm_string[2] == "C",
        )
        return perm_obj

    def serialize(self):
        ret = f"{self.group_id:04x}="
        prepr: dict[str, str] = {"read": "R", "write": "W", "receive": "C"}
        for perm, shorthand in prepr.items():
            ret += shorthand if getattr(self, perm) else "-"
        return ret


class PermissionList(list[Permission]):
    """
    @brief A collection of Permission objects with serialization support.
    """

    def __init__(self, *args: Permission):
        super().__init__()
        for item in args:
            self.append(item)

    @classmethod
    def deserialize(cls, perms: str):
        ret = cls()
        permissions_strings = perms.split(":")
        for entry in permissions_strings:
            perm_obj = Permission.deserialize(entry)
            ret.append(perm_obj)
        return ret

    def serialize(self):
        return ":".join(perm.serialize() for perm in self)


