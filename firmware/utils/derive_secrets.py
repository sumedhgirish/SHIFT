def key_as_array(
    groupid: int, secrets: dict[str, dict[str, dict[str, bytes]]], perm: str, sel: str
):
    """
    @brief Format a specific secret as a C-style array initializer list.

    @param groupid (int): The group ID to retrieve.
    @param secrets (dict): The secrets dictionary.
    @param sel (str): The selector ('internal' or 'external').

    @return str: The formatted C array.
    """
    return ", ".join([f"0x{b:02X}" for b in secrets[f"{groupid:04x}"][perm][sel]])


def interrogate_as_array(secrets: dict[str, dict[str, dict[str, bytes]]]):
    return ", ".join([f"0x{b:02X}" for b in secrets["global"]["interrogate"]["value"]])


