GEN_WRITEKEY: Callable[[int, dict[str, dict[str, dict[str, bytes]]]], str] = (
    lambda groupid, secrets: (
        f"""\
static StatusCode GenWriteKey_{groupid:04x}(uint8_t key[ASCON_KEY_SIZE])
{{
    KeyContext ctx = {{0}};
    static const uint8_t master_pub[MASTER_PUB_KEY_SIZE] = {{
        {key_as_array(groupid, secrets, "write", "master")}
    }};
    static const uint8_t tweak_secret[MASTER_KEY_SIZE] = {{
        {key_as_array(groupid, secrets, "write", "tweak")}
    }};

    randombytes(ctx.nonce, NONCE_SIZE);
    memcpy(ctx.id, (uint8_t *) &stage.as.file.metadata.fileid, ID_SIZE);
    memcpy(ctx.masterKey, tweak_secret, MASTER_KEY_SIZE);

    __disable_irq();
    apply_jitter();

    uint8_t s[ECC_PRIV_KEYSIZE];
    if (ascon_xof_masked(s, ECC_PRIV_KEYSIZE, (uint8_t *) &ctx, sizeof(ctx)) != 0)
    {{
        memclear((uint8_t *) &ctx, sizeof(ctx), 0x00);

        __enable_irq();
        return KEYGENERROR;
    }}

    apply_jitter();
    uint8_t eph_priv[ECC_PRIV_KEYSIZE];
    uint8_t eph_pub[ECC_PUB_KEYSIZE];
    if (uECC_make_key(eph_pub, eph_priv) != 1) {{

        memclear((uint8_t *) &ctx, sizeof(ctx), 0);
        memclear(s, ECC_PRIV_KEYSIZE, 0);

        __enable_irq();
        return KEYGENERROR;
    }}

    apply_jitter();
    uint8_t k_blind[ECC_PRIV_KEYSIZE];
    uECC_mod_mult(k_blind, eph_priv, s);

    uint8_t sharedSecret_raw[ECC_PRIV_KEYSIZE];
    if (uECC_shared_secret(master_pub, k_blind, sharedSecret_raw) != 1) {{

        memclear((uint8_t *) &ctx, sizeof(ctx), 0);
        memclear(s, ECC_PRIV_KEYSIZE, 0);
        memclear(eph_priv, ECC_PRIV_KEYSIZE, 0);
        memclear(eph_pub, ECC_PUB_KEYSIZE, 0);
        memclear(k_blind, ECC_PRIV_KEYSIZE, 0);

        __enable_irq();
        return KEYGENERROR;
    }}

    if (key != NULL)
        DeriveAsconKey(key, sharedSecret_raw);

    memcpy((uint8_t *) &stage.as.file.metadata.key, eph_pub, ECC_PUB_KEYSIZE);
    memcpy((uint8_t *) &stage.as.file.metadata.nonce, ctx.nonce, NONCE_SIZE);

    memclear((uint8_t *) &ctx, sizeof(ctx), 0);
    memclear(s, ECC_PRIV_KEYSIZE, 0);
    memclear(eph_priv, ECC_PRIV_KEYSIZE, 0);
    memclear(eph_pub, ECC_PUB_KEYSIZE, 0);
    memclear(k_blind, ECC_PRIV_KEYSIZE, 0);
    memclear(sharedSecret_raw, ECC_PRIV_KEYSIZE, 0);

    __enable_irq();
    return OPWRITE;
}}
"""
    )
)


